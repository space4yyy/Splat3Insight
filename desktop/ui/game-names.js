  // 繁体、英文和简体写法都对照到简体名称；查不到时返回 null，由调用方决定原样显示。
  const lookups = new Map();
  function lookup(kind, name) {
    const text = typeof name === 'string' ? name.trim() : '';
    if (!text || !TEXT[kind]) return null;
    if (!lookups.has(kind)) {
      const map = new Map();
      for (const [simplified, ...others] of TEXT[kind]) {
        map.set(simplified, simplified);
        for (const other of others) if (other) map.set(other, simplified);
      }
      lookups.set(kind, map);
    }
    return lookups.get(kind).get(text) ?? null;
  }

  // 称号是形容词加名词拼成的一句：中文直接连写（数据里的 "Thank You For " 自带空格），英文中间隔一个空格。
  // 从最长的形容词开始拆，两段都对得上时换成简体；拆不开时返回 null，由调用方原样显示。
  let titleParts = null;
  function title(name) {
    const text = typeof name === 'string' ? name.trim() : '';
    if (!text) return null;
    if (!titleParts) {
      const index = (rows) => {
        const map = new Map();
        for (const [simplified, ...others] of rows) for (const spelling of [simplified, ...others]) if (spelling) map.set(spelling.trim(), simplified);
        return map;
      };
      titleParts = { adjectives: index(TEXT.bynameAdjectives), subjects: index(TEXT.bynameSubjects) };
    }
    for (let end = text.length - 1; end > 0; end -= 1) {
      const adjective = titleParts.adjectives.get(text.slice(0, end).trim());
      const subject = adjective && titleParts.subjects.get(text.slice(end).trim());
      if (subject) return adjective + subject;
    }
    return null;
  }

  window.Splat3GameNames = Object.freeze({ text: TEXT, lookup, title });
